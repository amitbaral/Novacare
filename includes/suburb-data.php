/**
 * Get single suburb by key or slug
 */
function novacare_get_suburb_data( $identifier ) {
    $suburbs = novacare_get_suburbs_data();
    if ( isset( $suburbs[ $identifier ] ) ) {
        return $suburbs[ $identifier ];
    }
    foreach ( $suburbs as $key => $suburb ) {
        if ( $suburb['slug'] === $identifier || strtolower($suburb['name']) === strtolower($identifier) ) {
            return $suburb;
        }
    }
    return false;
}
